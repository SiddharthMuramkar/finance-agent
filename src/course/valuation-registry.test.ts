import { readFileSync } from "node:fs";
import { join } from "node:path";
import { describe, expect, it } from "vitest";
import { AMAZON_2000 } from "../finance/fixtures/amazon-2000.valuation";
import { VALUATION_CASES } from "../finance/valuation-cases.generated";
import { valuationBlock, valueCase } from "../finance/valuation-case";
import { loadCourseMap, type Topic } from "./map";
import { renderValuationCases, VALUATION_REGISTRY_PATH } from "./valuation-registry";

// The valuation Case registry (spec 2026-11-12 B1): what `npm run course:doc` writes from the Topic files' valuation blocks.

describe("the valuation Case registry", () => {
  it("holds Damodaran's Amazon of February 2000 from val-dcf, as Appendix B.1 gives it", () => {
    expect(VALUATION_CASES["amazon-dcf-2000"]).toEqual(AMAZON_2000);
    const valued = valueCase(valuationBlock.parse(VALUATION_CASES["amazon-dcf-2000"]));
    expect(valued.ok && Number(valued.valuePerShare.toFixed(2))).toBe(35.04);
  });

  it("is what the Topic files say, so a stale copy fails the course check", () => {
    expect(readFileSync(join(process.cwd(), VALUATION_REGISTRY_PATH), "utf8")).toBe(renderValuationCases(loadCourseMap().topics));
  });

  const block = valuationBlock.parse(AMAZON_2000);
  const topics = (cases: Topic["cases"]) => [{ cases }];
  const at = (id: string, extra: Partial<Topic["cases"][number]> = {}) => ({ id, title: id, data: [], asOf: "2000-02-01", story: "S.", reveal: "R.", ...extra });

  it("lists a borrowing Case under its own id too, every key sorted, and nothing for a Case with no block", () => {
    const file = renderValuationCases(topics([at("z-amazon", { valuation: block }), at("a-spine", { valuation: block, valuationFrom: "z-amazon" }), at("plain")]));
    expect([...file.matchAll(/^ {2}"([a-z-]+)": \{$/gm)].map((m) => m[1])).toEqual(["a-spine", "z-amazon"]);
    expect(file).not.toContain('"plain"');
  });

  it("starts with the generated header and the type import, and is empty when no Case has a block", () => {
    const file = renderValuationCases(topics([at("plain")]));
    expect(file.split("\n").slice(0, 2)).toEqual([
      "// Generated by npm run course:doc from the valuation: blocks in course/topics. Do not edit.",
      'import type { ValuationBlockInput } from "./valuation-case.ts";',
    ]);
    expect(file).toContain("export const VALUATION_CASES: Record<string, ValuationBlockInput> = {};");
  });
});
