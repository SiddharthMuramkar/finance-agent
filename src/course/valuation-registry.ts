import type { Topic } from "./map.ts";

// The valuation Case registry (spec 2026-11-12 B1, C2): every Topic file Case's `valuation:` block, written by
// `npm run course:doc` into src/finance/valuation-cases.generated.ts, so client and server code can value a Case by its
// id without reading course files (src/finance/valuation-cases.ts parses it). `npm run course:check` fails when the saved
// copy differs from what the Topic files say. No "@/" imports, so scripts/check-course.mjs can run it under plain Node.

/** Where the registry is written, from the repository root. */
export const VALUATION_REGISTRY_PATH = "src/finance/valuation-cases.generated.ts";

const IDENTIFIER = /^[A-Za-z_$][\w$]*$/;

/** A value as a TypeScript literal: flat arrays on one line, objects one key a line, keys unquoted when they can be. */
function literal(value: unknown, indent: string): string {
  const inner = `${indent}  `;
  if (Array.isArray(value)) {
    if (value.every((v) => v === null || typeof v !== "object")) return `[${value.map((v) => JSON.stringify(v)).join(", ")}]`;
    return `[\n${value.map((v) => `${inner}${literal(v, inner)},`).join("\n")}\n${indent}]`;
  }
  if (value !== null && typeof value === "object") {
    const entries = Object.entries(value).filter(([, v]) => v !== undefined);
    return `{\n${entries.map(([k, v]) => `${inner}${IDENTIFIER.test(k) ? k : JSON.stringify(k)}: ${literal(v, inner)},`).join("\n")}\n${indent}}`;
  }
  return JSON.stringify(value);
}

/**
 * The registry file: each Case with a valuation block, keyed by Case id and sorted by it. A Case that borrows its block
 * (`valuationFrom`) is listed under its own id too, with the block it borrows, so a Spine Topic's Case is found by the
 * id its Topic file gives it. Takes Topics as parseCourseMap returns them, with borrowed blocks filled in.
 */
export function renderValuationCases(topics: readonly Pick<Topic, "cases">[]): string {
  const blocks = topics
    .flatMap((t) => t.cases.flatMap((c) => (c.valuation ? [[c.id, c.valuation] as const] : [])))
    .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));
  const body = blocks.map(([id, block]) => `  ${JSON.stringify(id)}: ${literal(block, "  ")},`).join("\n");
  return [
    "// Generated by npm run course:doc from the valuation: blocks in course/topics. Do not edit.",
    'import type { ValuationBlockInput } from "./valuation-case.ts";',
    "",
    `export const VALUATION_CASES: Record<string, ValuationBlockInput> = {${body ? `\n${body}\n` : ""}};`,
    "",
  ].join("\n");
}
